<h2 class="seo-h2-custom">CORE COMPONENTS & FUNCTION</h2>
<p><strong>The Hoist Unit:</strong> This is the core of the system. It would consist of a motor, a lift wheel or a drum, and a lifting medium. The motor then drives the wind or unwind of the medium round the drum, thus lifting the hook that supports the load higher or lower.</p>
<p><strong>The Lifting Medium:</strong> Chain hoists are alloy chains of high strength, strong, compact and suitable to heavy repetitive lifting in extreme conditions such as foundries. Multi-strand steel cable hoists or wire rope hoists are more appropriate in higher capacity lifts and in large applications, since they are faster, smoother and possessing greater lifting heights.</p>
<p><strong>The Bridge:</strong> This is the structural beam on which the hoist moves giving the horizontal movement. In a crane overhead system, this bridge itself is frequently travelling on elevated runways and introduces a second direction in which it travels.</p>
<p><strong>The End Trucks:</strong> These are at the end of the bridge, which serves in moving the wheels that enable the whole crane to pass along the runway rails.</p>
<p><strong>The Hook:</strong> It is the main load-carrying member that comes into direct contact with the load. Its design plays a critical role in safety because it has to be able to carry safely slings, shackles or any other rigging hardware.</p>
