<p><strong>Safety Gear:</strong> It is devices to prevent the car in case of overspeed or rope failure.</p>
<p><strong>Buffer springs:</strong> These are found at the bottom of the shaft to minimise the impact in case the car falls too fast.</p>
<p><strong>Overspeed Governor:</strong> This is used to cheque the speed of cars and sparks safety gear when it is violated.</p>
<p><strong>Emergency Systems:</strong> Emergency light, manual rescue, emergency intercom/phone and alarm.</p>
<p><strong>Display & Control Panels:</strong> There will be buttons, displays and floor display (within the car and at each landing point).</p>
