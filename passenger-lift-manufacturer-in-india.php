<p><strong>Guide Rails:</strong> Steel tracks on which the car travels and counterweight so that the car moves easily and safely.</p>
<p><strong>Counterweight:</strong> This balances the weight of the car to minimise the load on the motor and increase the efficiency.</p>
<p><strong>Traction System / Hydraulic Ram:</strong> System that propels the lift (traction motor using ropes/belts or hydraulic piston).</p>
