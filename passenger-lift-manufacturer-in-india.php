<h2 class="seo-h2-custom">THE BASIC MECHANICS</h2>
<p>At its core, an elevator is a platform attached to a hoisting mechanism. The two primary systems are hydraulic and traction.</p>
<p><strong>Hydraulic Elevators:</strong> Common in low to mid-rise buildings, these elevators are powered by a hydraulic fluid and a piston. An electric pump forces fluid into the piston, which pushes the elevator car upwards. To descend, a valve opens, releasing the fluid back into a reservoir, allowing the car to lower by gravity. They are powerful but generally slower and less energy-efficient than traction systems.</p>
<p><strong>Traction Elevators:</strong> It is the system employed in the most high and middle-rise buildings. In a machine room, there is a heavy-duty electric motor that rotates a sheave. On one side the elevator car carries steel cables or belts, and on the other side a counterweight, which runs on this sheave. The load is counterbalanced by the counterweight which is approximately equal to the weight of the car and 40-50 percent of its weight which makes the task of the motor a lot easier and efficient. The modern traction elevators, in particular, machine-room-less (MRL) ones feature the motor located inside the shaft, which spares the building space.</p>
<p>Keeping these factors in mind, <strong>passenger lift manufacturers in India</strong> are continuously engaged not only in meeting the ever-increasing demand for high-quality lifts but also in improving their existing capabilities to improve performance and save energy at the same time. </p>
