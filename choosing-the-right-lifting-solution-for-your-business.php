                     <h4 class="mb-2">Application</h4>
                     <p><b>EOT Crane:</b> This crane is used where materials need to be lifted within specific confines, such as a warehouse or a factory. The device is suspended from the ceiling and has a set path in the form of an overhead runway. </p>
                     <p><b>Gantry Crane: </b> Gantry Cranes are versatile and can be used in different settings such as shipyards, construction sites, warehouses, and outdoor storage yards. It comes with self-supporting structures that can be moved indoors and outdoors as required by the user. </p>
