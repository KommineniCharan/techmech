                     <div class="mb-2">
                         <h4 class="mb-2">Mobility</h4>
                         <p><b>EOT Crane:</b> EOT Cranes can move along a predefined path only. They are built for specific tasks and have a designated work area. It is not built for mobility and is suited for repetitive tasks.</p>
                         <p><b>Gantry Crane: </b> These cranes can be relocated as needed since they come with self-supporting structures. It is suited for work areas where flexibility and mobility are a big factor.</p>
                     </div>
                     <div class="mb-2">
                         <h4 class="mb-2">Load</h4>
                         <p>Both cranes can be designed to handle varying load capacities depending on the requirement. The design and build of the cranes will determine how much load it can take at a point.</p>
                     </div>
                     <div class="mb-2">
                         <h4 class="mb-2">Cost</h4>
                         <p><b>EOT Crane:</b> EOT cranes are more cost-effective since their operations are limited and fixed. It is best suited for indoor applications where overhead runways are installed. Given its relatively limited functionality, the cost involved in building this device is also lower.</p>
                         <p><b>Gantry Crane: </b> These cranes are more expensive since they come with a self-supporting system and various features to improve their mobility and performance. It can be more cost-effective in workspaces where the crane is required in multiple locations.</p>
                     </div>
                     <div class="mb-2">
                         <h4 class="mb-2">Infrastructure</h4>
                         <p><b>EOT Crane:</b>  This crane is feasible in settings where there is a lot of vertical space and requires very limited mobility. </p>
                         <p><b>Gantry Crane: </b> Suited for businesses where vertical space is limited and requires a level surface for the crane to move on instead of overhead runways. </p>
                     </div>
                     <div class="mb-2">
                         <h4 class="mb-2">Environmental considerations</h4>
                         <p><b>EOT Crane:</b>   Well-suited for indoor settings where the assets are protected from the elements of nature.</p>
                         <p><b>Gantry Crane: </b> Suitable for outdoor applications and can weather the elements of nature.</p>
