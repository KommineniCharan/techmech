               <p><b>“TechMech Cranes”</b> make Freight Elevator
Freight Elevators (commonly called Goods Lift) are intended exclusively for vertical lifting of freight (Goods) in a cage which moves on rigid guide rails. This equipment finds applications where the material is to be shifted within different floors of a building or a workshop. Our manufacturing range consists of Lifting capacity from 0.5-ton upto 5.0-ton with a cage size ranging from 1.0 x 1.0 x 2.0 mtr. to 6.0 x 6.0 x 3.0 mtr. (WxDxH) Hoisting/Lowering of “TechMech Cranes” make Freight Elevators is done using fixed base mounted Twin Rope Drum Winch having a true vertical lift and with a unique feature called DUAL LOAD PATH SYSTEM to prevent fall of the cage in the unlikely event of rope failure and also at the same time it facilitates the use of the lift and gets the wire rope replaced at one’s convenience.
</p>
<p>Some of the safety features of our elevators are listed as under:</p>
<ul>
    <li>A Roller lever type floor limit switch will be provided to enable CAGE to maintain floor levels.</li>
    <li>Geared rotary type limit switch will be provided on the machine to prevent overtravel of the CAGE in the Top / Lowest floor level.</li>
    <li>A gravity type limit switch will be provided on the machine which will act as an extreme safety limit switch in the event of failure of any/all other above switches or even in the event of Push button contacts getting welded/stuck.</li>
</ul>
<p><b>“TechMech Cranes”</b> make Winch Stacker (Floor Lift)
</p>
<p>This design comprises an open platform suspended by its two ends from the fixed guided mast and has the lifting machinery either mounted on the top of the structure or suspended in the air along the mast. Thus, saving the overall structural cost as compared to the conventional elevators. The space required for installations is also less as compared to its counterpart and also solves the purpose of lifting/lowering material within floors. It can also be operated from any floor. Hence, a handy system for your material lifting needs.</p>
                
